#!/usr/bin/env node
/**
 * Idempotent reference catalogue → Postgres upsert SQL (run against DB by operators later).
 * Does not enable production sources or invoke connectors.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dir, '..', '..', '..');
const { REGULATORS, REGULATORY_SOURCES } = await import(
  pathToFileURL(join(repoRoot, 'packages', 'reference-data', 'index.mjs')).href,
);

function sqlLiteral(value) {
  if (value === null || value === undefined) return 'null';
  if (Array.isArray(value)) {
    if (value.length === 0) return 'array[]::text[]';
    return `array[${value.map((v) => sqlLiteral(v)).join(', ')}]::text[]`;
  }
  return `'${String(value).replace(/'/g, "''")}'`;
}

const lines = [
  '-- Generated by apps/platform/scripts/sync-reference-catalogue.mjs',
  '-- Upsert regulators and regulatory_sources from packages/reference-data',
  'begin;',
];

for (const r of REGULATORS) {
  lines.push(`
insert into public.regulators (
  external_key, name, acronym, jurisdiction, country, region, regulator_type,
  official_base_url, lifecycle_status
) values (
  ${sqlLiteral(r.regulatorId)},
  ${sqlLiteral(r.name)},
  ${sqlLiteral(r.acronym)},
  ${sqlLiteral(r.jurisdiction)},
  ${sqlLiteral(r.country)},
  ${sqlLiteral(r.region)},
  ${sqlLiteral(r.regulatorType)},
  ${sqlLiteral(r.officialBaseUrl)},
  ${sqlLiteral(r.status)}::public.catalogue_lifecycle_status
)
on conflict (external_key) do update set
  name = excluded.name,
  acronym = excluded.acronym,
  jurisdiction = excluded.jurisdiction,
  country = excluded.country,
  region = excluded.region,
  regulator_type = excluded.regulator_type,
  official_base_url = excluded.official_base_url,
  lifecycle_status = excluded.lifecycle_status,
  updated_at = now();`);
}

for (const s of REGULATORY_SOURCES) {
  const integration = s.integration ?? {};
  const productionStatus = integration.productionStatus ?? 'NOT_ENABLED';
  const verification = integration.verificationStatus ?? 'NOT_TESTED';
  const coverage = integration.coverageVerificationStatus ?? 'NOT_TESTED';
  const contentClasses = integration.contentClasses ?? [];
  const riUses = integration.riUseCases ?? [];
  const displayName = `${s.regulatorName} — ${s.sourceId}`;
  const canonicalUrl =
    integration.canonicalRegulatoryContentUrl ?? s.officialBaseUrl ?? null;

  lines.push(`
insert into public.regulatory_sources (
  external_key, regulator_id, name, source_type, canonical_url, jurisdiction,
  catalogue_status, verification_status, coverage_verification_status,
  production_status, production_strategy, content_classes, ri_uses
) select
  ${sqlLiteral(s.sourceId)},
  r.id,
  ${sqlLiteral(displayName)},
  ${sqlLiteral(s.sourceType)},
  ${sqlLiteral(canonicalUrl)},
  ${sqlLiteral(s.jurisdiction)},
  ${sqlLiteral(s.status)}::public.catalogue_lifecycle_status,
  ${sqlLiteral(verification)}::public.integration_verification_status,
  ${sqlLiteral(coverage)}::public.coverage_verification_status,
  ${sqlLiteral(productionStatus)}::public.production_source_status,
  ${sqlLiteral(integration.productionStrategy ?? null)},
  ${sqlLiteral(contentClasses)}::text[],
  ${sqlLiteral(riUses)}::text[]
from public.regulators r
where r.external_key = ${sqlLiteral(s.regulatorId)}
on conflict (external_key) do update set
  name = excluded.name,
  source_type = excluded.source_type,
  canonical_url = excluded.canonical_url,
  jurisdiction = excluded.jurisdiction,
  catalogue_status = excluded.catalogue_status,
  verification_status = excluded.verification_status,
  coverage_verification_status = excluded.coverage_verification_status,
  production_status = excluded.production_status,
  production_strategy = excluded.production_strategy,
  content_classes = excluded.content_classes,
  ri_uses = excluded.ri_uses,
  updated_at = now();`);
}

lines.push('commit;');

const outPath = join(__dir, '..', 'supabase', 'seed', 'reference-catalogue.generated.sql');
writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`Wrote ${outPath} (${REGULATORS.length} regulators, ${REGULATORY_SOURCES.length} sources)`);
