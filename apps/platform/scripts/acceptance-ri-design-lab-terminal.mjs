#!/usr/bin/env node
/**
 * Design Lab terminal UI contract (Production Readiness Phase 12). Deterministic, no browser, no network.
 *
 * Proves: the quick-view detail model never invents values and only trusts https source links; the modal
 * and button markup escape hostile input; the stylesheet really provides a centred modal with a blurred
 * backdrop, emerald-on-charcoal tokens, reduced-motion handling and WCAG AA contrast for the pairs it
 * documents; both views are wired; and the legacy /ri/* frontend was not touched.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  DETAIL_KINDS,
  buildObligationDetail,
  buildPublicationDetail,
} from '../../../design-lab/regulatory-intelligence/js/terminal-detail-model.js';

const platformRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
// design-lab/ is the source of truth; apps/platform/design-lab-bundle is generated by prebuild (sync-design-lab-bundle.mjs).
const lab = join(platformRoot, '..', '..', 'design-lab', 'regulatory-intelligence');
const bundle = join(platformRoot, 'design-lab-bundle', 'regulatory-intelligence');
let pass = 0;
let fail = 0;
function check(name, cond, detail = '') {
  if (cond) pass += 1;
  else {
    fail += 1;
    console.error(`FAIL ${name}${detail ? ` :: ${detail}` : ''}`);
  }
}
const read = (p) => readFileSync(join(lab, p), 'utf8');

// ---------------------------------------------------------------- model
const fmt = (d) => `D(${d})`;
const pub = buildPublicationDetail(
  {
    id: 'p-1',
    regulator: 'FCA',
    title: 'Consumer Duty',
    publishedDate: '2026-01-02',
    effectiveDate: null,
    display: { reference: 'PS22/9', topic: 'Retail', publicationType: 'Policy Statement', libraryVersion: '1.0', libraryStatus: 'Current' },
    _detail: { summary: 'S', canonicalUrl: 'https://www.fca.org.uk/x' },
  },
  fmt,
);
check('pub: kind and href', pub.kind === 'publication' && pub.fullHref === '#/publication/p-1');
check('pub: formats dates through supplied formatter', pub.fields.find((f) => f.label === 'Published').value === 'D(2026-01-02)');
check('pub: absent effective date is a dash, not invented', pub.fields.find((f) => f.label === 'Effective').value === '—');
check('pub: https source accepted', pub.sourceUrl === 'https://www.fca.org.uk/x');
for (const bad of ['http://x.example', 'javascript:alert(1)', 'data:text/html,x', '//evil.example', '']) {
  const m = buildPublicationDetail({ id: 'p', title: 't', _detail: { canonicalUrl: bad } });
  check(`pub: non-https source rejected (${bad || 'empty'})`, m.sourceUrl === null);
}
check('pub: id is URL-encoded in href', buildPublicationDetail({ id: 'a/b?c', title: 't' }).fullHref === '#/publication/a%2Fb%3Fc');
check('pub: missing record or id gives null', buildPublicationDetail(null) === null && buildPublicationDetail({}) === null);

const long = 'x'.repeat(300);
const obl = buildObligationDetail({ id: 'abcdef123456', externalKey: 'OBL-1', statement: long, status: 'OPEN', priority: 'High', dataProvenance: 'uat_authorised' }, fmt);
check('obl: title truncated but full statement retained as summary', obl.title.length === 161 && obl.summary === long);
check('obl: badges carry status and priority', obl.badges.join() === 'OPEN,High');
check('obl: provenance surfaced (UAT records are distinguishable)', obl.fields.find((f) => f.label === 'Provenance').value === 'uat_authorised');
check('obl: key falls back to id prefix', buildObligationDetail({ id: 'abcdef123456', title: 't' }).eyebrow === 'abcdef12');
check('obl: no external source link is ever produced', obl.sourceUrl === null);
check('kinds are exactly publication and obligation', DETAIL_KINDS.join() === 'publication,obligation');

// ---------------------------------------------------------------- markup escaping (modal module imports the store, so load it lazily)
let markup = null;
try {
  globalThis.window ??= { addEventListener() {}, location: { hash: '' }, localStorage: { getItem: () => null, setItem() {}, removeItem() {} } };
  globalThis.document ??= { addEventListener() {}, getElementById: () => null };
  globalThis.localStorage ??= globalThis.window.localStorage;
  markup = await import('../../../design-lab/regulatory-intelligence/js/terminal-detail-modal.js');
} catch (e) {
  check('modal module loads under Node stub', false, String(e?.message || e));
}
if (markup) {
  const hostile = buildPublicationDetail({ id: 'p"><img src=x onerror=1>', regulator: '<b>R</b>', title: '"><script>1</script>', display: { reference: '<i>' }, _detail: { summary: '<svg onload=1>' } });
  const html = markup.renderDetailMarkup(hostile);
  check('markup: no raw tags from data', !/<script|<img|<svg|<b>|<i>/.test(html));
  check('markup: dialog title is labelled target', html.includes('id="ri-terminal-detail-title"'));
  check('markup: primary link and close button present', html.includes('data-ri-detail-open') && html.includes('data-ri-detail-close'));
  const btn = markup.peekButton('publication', 'p"><x', 'T"><y');
  check('peekButton: escapes attributes', !/"><x|"><y/.test(btn) && btn.includes('aria-haspopup="dialog"'));
  check('peekButton: rejects unknown kind or missing id', markup.peekButton('risk', 'x') === '' && markup.peekButton('publication', '') === '');
}

// ---------------------------------------------------------------- stylesheet contract
const css = read('css/ri-terminal.css');
check('css: modal is centred (fixed, inset 0, margin auto)', /\.ri-terminal-modal\s*\{[^}]*position:\s*fixed;[^}]*inset:\s*0;[^}]*margin:\s*auto;/s.test(css));
check('css: blurred backdrop', /\.ri-terminal-modal::backdrop\s*\{[^}]*backdrop-filter:\s*blur\(\d+px\)/s.test(css));
check('css: backdrop has an opaque fallback without backdrop-filter', /@supports not[\s\S]*::backdrop/.test(css));
check('css: reduced motion honoured', /prefers-reduced-motion:\s*reduce[\s\S]*animation:\s*none/.test(css));
check('css: mobile layout', /max-width:\s*640px/.test(css));
check('css: scoped (no unscoped body/html/* selectors)', !/^\s*(body|html|\*)\s*[,{]/m.test(css));
check('css: visible focus styles', (css.match(/focus-visible/g) || []).length >= 3);
check('css: emerald accent token', /--rt-emerald:\s*#34d399/i.test(css) && /--rt-bg:\s*#0c0f12/i.test(css));

function luminance(hex) {
  const n = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
function ratio(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}
const panel = '#12161b';
const bg = '#0c0f12';
const pairs = { text: '#dde3e9', muted: '#93a0ac', emerald: '#34d399', amber: '#fbbf24', red: '#f87171' };
for (const [name, hex] of Object.entries(pairs)) {
  check(`contrast AA on panel: ${name}`, ratio(hex, panel) >= 4.5, ratio(hex, panel).toFixed(2));
  check(`contrast AA on page background: ${name}`, ratio(hex, bg) >= 4.5, ratio(hex, bg).toFixed(2));
}
check('contrast AA: primary button label on emerald', ratio('#04120c', '#34d399') >= 4.5, ratio('#04120c', '#34d399').toFixed(2));
check('css documents the tokens it uses', css.includes('#dde3e9') && css.includes('#93a0ac'));

const riCss = read('css/ri.css');
check(
  'ri.css dark scroll: 4px sidebar rail + hover thumb',
  /--ri-scroll-size:\s*4px/.test(riCss) &&
    /\.ri-sidebar::-webkit-scrollbar-thumb/.test(riCss) &&
    /\.ri-sidebar:hover::-webkit-scrollbar-thumb/.test(riCss) &&
    /\.ri-calendar-rail::-webkit-scrollbar/.test(riCss) &&
    /scrollbar-gutter:\s*stable/.test(riCss),
);

// ---------------------------------------------------------------- wiring
const html = read('index.html');
const views = read('js/views.js');
const app = read('js/app.js');
check('index.html links the terminal stylesheet', html.includes('/css/ri-terminal.css'));
check('views: Publications wrapped and wired', /data-ri-terminal="publications"/.test(views) && /data-ri-detail-row="publication"/.test(views) && /peekButton\('publication'/.test(views));
check('views: Obligations wrapped and wired (operational and UAT tables)', /data-ri-terminal="obligations"/.test(views) && (views.match(/data-ri-detail-row="obligation"/g) || []).length === 2);
check('views: existing search and table ids preserved', views.includes('id="library-search"') && views.includes('id="library-table-body"'));
check('app: binds the detail modal once', app.includes("import { bindTerminalDetail }") && /function bindViewHandlers\(\) \{\s*bindTerminalDetail\(\);/.test(app));
check('modal module present', existsSync(join(lab, 'js/terminal-detail-modal.js')));

// ---------------------------------------------------------------- source and generated bundle are in step
for (const f of ['css/ri-terminal.css', 'js/terminal-detail-model.js', 'js/terminal-detail-modal.js', 'js/views.js', 'js/app.js', 'index.html']) {
  const inSync = existsSync(join(bundle, f)) && readFileSync(join(bundle, f), 'utf8') === read(f);
  check(`bundle in sync with source: ${f}`, inSync, 'run: node scripts/sync-design-lab-bundle.mjs');
}

// ---------------------------------------------------------------- legacy frontend untouched
try {
  const out = execFileSync('git', ['status', '--porcelain', '--', 'app/ri', 'components/ri'], { cwd: platformRoot, encoding: 'utf8' });
  check('legacy /ri/* frontend has no changes', out.trim() === '', out.trim());
} catch (e) {
  check('legacy frontend check could run', false, String(e?.message || e));
}

console.log(`Design Lab terminal acceptance: ${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
