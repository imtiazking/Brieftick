import { REGULATORS } from './regulators.mjs';
import { attachSourceIntegration } from './source-integration.mjs';

const byId = Object.fromEntries(REGULATORS.map((r) => [r.regulatorId, r]));

/**
 * @param {string} regulatorId
 * @param {Partial<import('./types.mjs').RegulatorySourceRecord>} source
 */
function source(regulatorId, source) {
  const r = byId[regulatorId];
  if (!r) throw new Error(`Unknown regulatorId ${regulatorId}`);
  const record = {
    regulatorId,
    regulatorName: r.name,
    acronym: r.acronym,
    jurisdiction: r.jurisdiction,
    country: r.country,
    region: r.region,
    regulatorType: r.regulatorType,
    regulatoryDomains: [...r.regulatoryDomains],
    sectors: [...r.sectors],
    officialBaseUrl: source.officialBaseUrl || r.officialBaseUrl,
    ...source,
  };
  return attachSourceIntegration(record);
}

