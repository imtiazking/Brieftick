/**
 * @param {import('./types.mjs').RegulatorySourceRecord} record
 */
function mergeCoverage(sourceId, integration) {
  const coverage = SOURCE_COVERAGE_BY_ID[sourceId];
  if (!coverage) {
    return {
      ...integration,
      coverageVerificationStatus: 'NOT_TESTED',
    };
  }
  const lineage = SOURCE_LINEAGE_BY_ID[sourceId];
  return {
    ...integration,
    coverageVerificationStatus: coverage.coverageVerificationStatus,
    contentClasses: coverage.contentClasses,
    riUseCases: coverage.riUseCases,
    coverageNotes: coverage.coverageNotes,
    catalogueRecommendation: coverage.catalogueRecommendation,
    missingEndpointHint: coverage.missingEndpointHint,
    ...(lineage ? { sourceLineage: lineage } : {}),
  };
}

export function attachSourceIntegration(record) {
  const integration = SOURCE_INTEGRATION_BY_ID[record.sourceId];
  if (!integration) {
    return {
      ...record,
      integration: {
        verificationStatus: 'NOT_TESTED',
        productionStatus: 'NOT_ENABLED',
        coverageVerificationStatus: 'NOT_TESTED',
      },
    };
  }
  return { ...record, integration: mergeCoverage(record.sourceId, integration) };
}
